"""
Модуль загрузки данных о поставщиках
"""

import pandas as pd
from pathlib import Path


def load_data():
    """
    Загрузка данных о поставщиках из CSV файла.
    Если файл не найден, создает демо-данные.
    """
    # Путь к файлу с данными
    data_path = Path(__file__).parent.parent / "data" / "suppliers.csv"
    
    # Проверяем, существует ли файл
    if not data_path.exists():
        print(f"⚠️ Файл {data_path} не найден. Создаем демо-данные.")
        return _create_demo_data()
    
    try:
        # Загружаем данные
        df = pd.read_csv(data_path)
        print(f"✅ Загружено {len(df)} поставщиков из {data_path}")
        
        # Заполняем пропуски
        for col in ['price_range', 'min_order', 'delivery_conditions', 'region', 
                    'contacts', 'website', 'documents', 'notes']:
            if col in df.columns:
                df[col] = df[col].fillna('не указано')
        
        return df
        
    except Exception as e:
        print(f"❌ Ошибка загрузки данных: {e}")
        return _create_demo_data()


